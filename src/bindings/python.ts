/**
 * Python binding: the six language-specific things, as templates against upstream
 * packages only (`mcp` 2.x + pydantic 2, and the standard library for the CLI). The
 * kernel files under `src/<pkg>/toolfactory/` are regenerated on every build; the
 * author's `src/<pkg>/ops.py` is scaffolded once and then owned.
 */
