/** The one artifact the `package` job uploads and every later job reads. */
const RELEASE_ARTIFACT = "release-assets";

type Step = Record<string, unknown>;

function yml(document: unknown): string {
  // lineWidth: 0 disables folding — a long `run:` one-liner stays one line instead of being
  // wrapped mid-command, which would still parse but reads (and diffs) badly.
  // aliasDuplicateObjects: false — shared step objects must not become YAML anchors.
  return yamlStringify(document, { lineWidth: 0, aliasDuplicateObjects: false });
}

/**
 * The tag `release.yml` is releasing. On `push: tags` it is the pushed tag; on `workflow_dispatch`
 * it is the `tag` input — either an existing tag (the operator's re-run after minting a missing
 * secret, which `gh run rerun` cannot be because a re-run replays the original run's secret
 * snapshot) or a new one, cut at the dispatched branch's head by the Release itself. `gate`
 * resolves the commit once (`outputs.sha`); every other checkout, the assert, the image tag and
 * the Release read it, so a dispatched run releases that commit and never the branch's later head.
 */
const TAG_NAME = "${{ inputs.tag || github.ref_name }}";
const RELEASE_SHA = "${{ needs.gate.outputs.sha }}";

/** `actions/checkout`, pinned to the released tag inside `release.yml` and to the event elsewhere. */
function checkoutStep(ref?: string, extra?: Record<string, unknown>): Step {
  const options = compact({ ref, ...extra });
  return compact({
    uses: "actions/checkout@v7",
    with: Object.keys(options).length ? options : undefined,
  });
}

/** A single job dependency as GitHub Actions spells it: a bare string for one, an array for many. */
function needsOf(jobs: string[]): string | string[] | undefined {
  if (jobs.length === 0) return undefined;
  // A copy: callers keep pushing onto the leg list after reading it.
  return jobs.length === 1 ? jobs[0] : [...jobs];
}

