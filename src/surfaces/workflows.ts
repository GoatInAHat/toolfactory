/**
 * Which registries this tag can publish to, decided once. Each gated row's `gate` runs with that
 * row's secrets and confirm variable in its environment and the answer becomes a job output,
 * because `secrets` and `env` are unreadable in a job-level `if` and the reusable-workflow legs
 * cannot be gated inside a `run:`. A row that cannot publish prints one notice pointing at its page.
 */
function presenceStep(rows: Registry[]): Step {
  const gated = rows.filter((row) => row.gate);
  const env: Record<string, string> = { GH_TOKEN: "${{ github.token }}" };
  for (const row of gated) {
    for (const name of row.secrets) env[name] = `\${{ secrets.${name} }}`;
    if (row.confirmVariable) env[row.confirmVariable] = `\${{ vars.${row.confirmVariable} }}`;
  }
  const script = gated.map((row) => {
    const v = gateVariable(row);
    return `${v}=false; if ${row.gate}; then ${v}=true; else echo "::notice::${row.id}: not published at this tag — ${row.url}"; fi; echo "${v}=$${v}" >> "$GITHUB_OUTPUT"`;
  });
  return {
    id: "presence",
    name: "which registries this tag can publish to",
    env,
    run: script.join("\n"),
  };
}

function presenceOutputs(rows: Registry[]): Record<string, string> | undefined {
  const gated = rows.filter((row) => row.gate);
  return gated.length
    ? Object.fromEntries(
        gated.map((row) => [
          gateVariable(row),
          `\${{ steps.presence.outputs.${gateVariable(row)} }}`,
        ]),
      )
    : undefined;
}

function releaseDocument(
  project: Project,
): { doc: Record<string, unknown>; comments: string[] } | undefined {
  const npmSelected = has(project, "npm");
  const pypiSelected = has(project, "pypi");
  const mcpRegistrySelected = has(project, "mcp-registry");
  // ClawHub publishes the openclaw-native package; without that host there is nothing to publish.
  const clawhubSelected = has(project, "clawhub") && has(project, "openclaw-native");
  // ClawHub's skill catalog is a separate track from its plugin catalog above: it publishes
  // straight from the checkout (no openclaw-native package needed), so `skill` is all it takes.
  const clawhubSkillSelected = has(project, "clawhub") && has(project, "skill");
  const browserExtSelected = has(project, "browser-extension");
  const rows = registries(project);
  const gated = (id: Registry["id"]): string | undefined => {
    const row = rows.find((entry) => entry.id === id);
    return row?.gate ? `needs.gate.outputs.${gateVariable(row)} == 'true'` : undefined;
  };

  const pm = PACKAGE_MANAGER_COMMANDS[project.packageManager ?? "npm"];
  const cli = toolfactoryCli(project);
  const assert = tagVersionAssert(project);
  const jobs: Record<string, unknown> = {
    gate: compact({
      "runs-on": "ubuntu-latest",
      permissions: compact({ contents: "read", pages: has(project, "web") ? "read" : undefined }),
      env: { RELEASE_TAG: TAG_NAME },
      outputs: { sha: "${{ steps.tag.outputs.sha }}", ...presenceOutputs(rows) },
      steps: [
        // The whole history: the tag may exist (a re-run) or not yet (a dispatch cuts it), and
        // `unpublish` reads tool.json at the previous tag.
        checkoutStep(undefined, { "fetch-depth": 0 }),
        ...toolchainSteps(project, "24").slice(1),
        {
          id: "tag",
          name: "the commit this tag releases",
          run: 'sha=$(git rev-parse -q --verify "refs/tags/$RELEASE_TAG^{commit}" 2>/dev/null || git rev-parse HEAD) && git checkout -q "$sha" && echo "sha=$sha" >> "$GITHUB_OUTPUT"',
        },
        ...(assert ? [actionStep(assert, false)] : []),
        ...hermesSteps(project),
        ...gateSteps(project).map((step) => actionStep(step, false)),
        presenceStep(rows),
      ],
    }),
    package: compact({
      needs: "gate",
      "runs-on": "ubuntu-latest",
      permissions: { contents: "read" },
      // The Firefox self-hosted xpi packageSteps emits (gate.ts) is opt-in on this pair: present,
      // it signs; absent, that one step no-ops and the job still packages the unsigned zips.
      env: has(project, "browser-extension")
        ? {
            FIREFOX_JWT_ISSUER: "${{ secrets.FIREFOX_JWT_ISSUER }}",
            FIREFOX_JWT_SECRET: "${{ secrets.FIREFOX_JWT_SECRET }}",
          }
        : undefined,
      steps: [
        ...toolchainSteps(project, "24", RELEASE_SHA),
        ...packageSteps(project).map((step) => actionStep(step, false)),
        {
          uses: "actions/upload-artifact@v7",
          with: { name: RELEASE_ARTIFACT, path: `${RELEASE_DIR}/` },
        },
      ],
    }),
  };
  const priorLegs: string[] = [];

  if (npmSelected) {
    jobs["publish-npm"] = compact({
      needs: "gate",
      if: gated("npm"),
      "runs-on": "ubuntu-latest",
      permissions: { "id-token": "write", contents: "read" },
      env: { NPM_TOKEN: "${{ secrets.NPM_TOKEN }}" },
      steps: [
        checkoutStep(RELEASE_SHA),
        ...SETUP_ACTIONS[project.packageManager ?? "npm"],
        {
          uses: "actions/setup-node@v7",
          with: { "node-version": "24", "registry-url": "https://registry.npmjs.org" },
        },
        { run: `${pm.install} && ${pm.run("build")}` },
        // A name already on the registry publishes through trusted publishing (OIDC; npm generates
        // the provenance itself, so no `--provenance`). A brand-new name cannot — `npm trust`
        // refuses it — so only that branch exports the token, and setup-node's placeholder
        // NODE_AUTH_TOKEN never masquerades as one.
        {
          name: "npm publish",
          run: `if ${npmPackageExists(project)}; then npm publish --access public; else NODE_AUTH_TOKEN="$NPM_TOKEN" npm publish --access public; fi`,
        },
      ],
    });
    priorLegs.push("publish-npm");
  }
  if (pypiSelected) {
    jobs["publish-pypi"] = compact({
      needs: "gate",
      if: gated("pypi"),
      "runs-on": "ubuntu-latest",
      environment: "pypi",
      permissions: { "id-token": "write" },
      steps: [
        checkoutStep(RELEASE_SHA),
        { uses: "astral-sh/setup-uv@v6" },
        { run: "uv build" },
        {
          name: "Publish package distributions to PyPI",
          uses: "pypa/gh-action-pypi-publish@release/v1",
        },
      ],
    });
    priorLegs.push("publish-pypi");
  }
  const owner = githubOwner(project.identity.repository);
  if (mcpRegistrySelected && owner) {
    // The image the `mcp-registry` surface already named in `server.json`'s oci entry, and the
    // root Dockerfile it emitted alongside it. `type=semver` turns the v-prefixed tag into the
    // bare version the entry carries — the gate has already asserted they agree.
    const image = ociImage(project, owner).replace(/:[^:]*$/, "");
    jobs["publish-oci"] = compact({
      needs: "gate",
      if: gated("oci"),
      "runs-on": "ubuntu-latest",
      permissions: {
        contents: "read",
        packages: "write",
        attestations: "write",
        "id-token": "write",
      },
      steps: [
        checkoutStep(RELEASE_SHA),
        {
          uses: "docker/login-action@v4",
          with: {
            registry: "ghcr.io",
            username: "${{ github.actor }}",
            password: "${{ secrets.GITHUB_TOKEN }}",
          },
        },
        {
          id: "meta",
          uses: "docker/metadata-action@v6",
          with: {
            images: image,
            tags: `type=semver,pattern={{version}},value=${TAG_NAME}`,
            // The registry's OCI ownership check reads this label back out of the image config.
            labels: `io.modelcontextprotocol.server.name=${registryName(project)}`,
          },
        },
        {
          uses: "docker/build-push-action@v7",
          with: {
            context: ".",
            push: true,
            tags: "${{ steps.meta.outputs.tags }}",
            labels: "${{ steps.meta.outputs.labels }}",
          },
        },
      ],
    });
    priorLegs.push("publish-oci");
  }
  if (mcpRegistrySelected) {
    jobs["publish-mcp-registry"] = compact({
      // After every package leg (§7): mcp-publisher validates that each `packages[]` entry
      // already exists in its own registry, the oci image included — so the gate lets it run only
      // when every package leg does.
      needs: needsOf(priorLegs.length ? priorLegs : ["gate"]),
      if: gated("mcp-registry"),
      "runs-on": "ubuntu-latest",
      permissions: { "id-token": "write", contents: "read" },
      steps: [
        checkoutStep(RELEASE_SHA),
        { run: MCP_PUBLISHER_FETCH },
        { run: "./mcp-publisher login github-oidc && ./mcp-publisher publish" },
      ],
    });
    priorLegs.push("publish-mcp-registry");
  }
  const comments = [
    "`gate` decides once which registries this tag can publish to (a job-level `if` cannot read",
    "secrets) and every leg obeys its output, so a tag with no secrets is still green: gate,",
    "package, the Release, and whatever else applies. After adding a secret, re-run with",
    "`gh workflow run release.yml -f tag=vX.Y.Z` — never `gh run rerun`, which replays the",
    "original run's secret snapshot. `release` first retracts every registry a surface dropped",
    "since the previous tag published to (git is the ledger; `toolfactory unpublish`), and",
    "`toolfactory secrets status` / `bootstrap-repo` cover the one-time steps that are left.",
  ];
  if (clawhubSelected) {
    jobs["publish-clawhub"] = compact({
      if: gated("clawhub-package"),
      // Last (§7): content-fingerprint deduped by ClawHub, therefore safe to retry. The reusable
      // workflow has no build step, so it publishes the tarball the `package` job already built
      // rather than the repository subdirectory. It is a workflow call, so it has no `permissions`
      // block of its own and inherits the file's `contents: read`.
      needs: needsOf(["package", ...priorLegs]),
      uses: "openclaw/clawhub/.github/workflows/package-publish.yml@main",
      with: {
        package_artifact_name: RELEASE_ARTIFACT,
        package_artifact_path: openclawTarball(project),
        dry_run: false,
        wait_for_publication: true,
      },
      secrets: { clawhub_token: "${{ secrets.CLAWHUB_TOKEN }}" },
    });
    priorLegs.push("publish-clawhub");
    comments.push(
      "",
      "ClawHub's GitHub-OIDC trusted publishing covers `workflow_dispatch` only, not",
      "`push: tags` — this leg is the one that is not secretless (§7): it needs a stored",
      "CLAWHUB_TOKEN repo secret, and `clawhub package trusted-publisher set` does not help here.",
    );
  }
  if (clawhubSkillSelected) {
    // A separate ClawHub track from the package leg above: publishes skills/<N> to ClawHub's
    // skill catalog straight from the checkout, so it only needs `gate`, not the built tarball.
    // ClawHub's own reusable workflow derives slug/name/version from SKILL.md and dedupes by
    // content fingerprint, same as `clawhub package publish` above — safe to retry.
    jobs["publish-clawhub-skill"] = compact({
      if: gated("clawhub-skill"),
      needs: "gate",
      uses: "openclaw/clawhub/.github/workflows/skill-publish.yml@main",
      with: { skill_path: skillPath(project).replace(/\/SKILL\.md$/, ""), dry_run: false },
      secrets: { clawhub_token: "${{ secrets.CLAWHUB_TOKEN }}" },
    });
    priorLegs.push("publish-clawhub-skill");
    comments.push(
      "",
      "ClawHub skill publishing has no OIDC trusted-publishing path yet (V1 is token-only,",
      "per its own docs) — this leg reuses the same stored CLAWHUB_TOKEN as publish-clawhub.",
    );
  }
  if (browserExtSelected) {
    jobs["publish-browser-ext"] = browserExtPublishJob(project, rows);
    priorLegs.push("publish-browser-ext");
    comments.push(
      "",
      "None of Chrome Web Store, Firefox Add-ons or Edge Add-ons supports GitHub OIDC — like",
      "CLAWHUB_TOKEN above, publish-browser-ext is a stored-secrets leg, gated per store on that",
      "store's own secrets (nine names across the three stores); a store left unconfigured is",
      "skipped, never a failure, and the leg's own dry run runs on every push and pull request.",
    );
    const safari = rows.find((row) => row.id === "safari");
    if (safari) {
      // Opt-in and outside the release graph on purpose: it submits to App Store Connect, not
      // dist/release/, so nothing downstream needs to wait on it.
      jobs["publish-browser-ext-safari"] = browserExtSafariJob(project, safari);
      comments.push(
        "",
        "publish-browser-ext-safari (opt-in, tool.json browserExtension.safari) is the macOS",
        "host-native leg: xcrun safari-web-extension-converter, then an Xcode archive/export",
        "signed with an App Store Connect API key. Runs on macos-latest, needs only `gate`, and",
        "does not gate the release — it submits to App Store Connect, not dist/release/.",
      );
    }
  }

  jobs.release = {
    // The tag's own release, after every leg: the assets are the same ones the registries got.
    // Skipped legs must not skip it, only failed ones; hence the explicit condition.
    needs: needsOf(["package", ...priorLegs]),
    if: "${{ !cancelled() && needs.package.result == 'success' && !contains(needs.*.result, 'failure') }}",
    "runs-on": "ubuntu-latest",
    // Retraction needs what publishing needed: packages and pages to delete, OIDC for the MCP
    // registry, and the stored tokens the dropped registries' rows name.
    permissions: { contents: "write", packages: "write", pages: "write", "id-token": "write" },
    env: {
      RELEASE_TAG: TAG_NAME,
      GH_TOKEN: "${{ github.token }}",
      ...Object.fromEntries(RELEASE_SECRET_NAMES.map((name) => [name, `\${{ secrets.${name} }}`])),
    },
    steps: [
      // The whole history: `unpublish` reads tool.json at the previous tag.
      checkoutStep(RELEASE_SHA, { "fetch-depth": 0 }),
      ...toolchainSteps(project, "24", RELEASE_SHA).slice(1),
      ...bootstrapSteps(project).map((step) => actionStep(step, false)),
      actionStep(unpublishStep(project), false),
      {
        uses: "actions/download-artifact@v8",
        with: { name: RELEASE_ARTIFACT, path: RELEASE_ARTIFACT },
      },
      {
        uses: "softprops/action-gh-release@v3",
        with: {
          tag_name: TAG_NAME,
          // A tag the dispatch is cutting does not exist yet: the Release creates it here.
          target_commitish: RELEASE_SHA,
          generate_release_notes: true,
          files: `${RELEASE_ARTIFACT}/*`,
          fail_on_unmatched_files: true,
        },
      },
    ],
  };

  if (has(project, "web")) {
    jobs["pages-build"] = compact({
      needs: "gate",
      if: gated("pages"),
      "runs-on": "ubuntu-latest",
      permissions: { contents: "read" },
      steps: [
        ...toolchainSteps(project, "24", RELEASE_SHA),
        ...[...bootstrapSteps(project), outputsStep(project)].map((step) =>
          actionStep(step, false),
        ),
        { uses: "actions/configure-pages@v5" },
        {
          name: "web build",
          // A project page is served from /<repo>/, so Vite's base has to say so or every asset
          // 404s. `web/vite.config.ts` reads PAGES_BASE and defaults to "/" for `npm run dev`.
          env: { PAGES_BASE: "/${{ github.event.repository.name }}/" },
          run: WEB_BUILD,
        },
        {
          name: "publish the schema and the coverage report alongside the app",
          run: `cp dev.toolfactory/tool.schema.json COVERAGE.md web/dist/ && ${cli} coverage > web/dist/coverage.json`,
        },
        { uses: "actions/upload-pages-artifact@v3", with: { path: "web/dist" } },
      ],
    });
    jobs["pages-deploy"] = {
      needs: "pages-build",
      "runs-on": "ubuntu-latest",
      permissions: { pages: "write", "id-token": "write" },
      environment: { name: "github-pages", url: "${{ steps.deployment.outputs.page_url }}" },
      steps: [{ id: "deployment", uses: "actions/deploy-pages@v5" }],
    };
    comments.push(
      "",
      "Pages must be enabled with Source = GitHub Actions once (`toolfactory bootstrap-repo` does",
      "it through gh); until then the gate skips the Pages pair with a notice.",
    );
  }

  const doc = {
    name: "Release",
    on: {
      push: { tags: ["v*"] },
      workflow_dispatch: {
        inputs: {
          tag: {
            description: "The v* tag to release: an existing one to publish again (e.g. after adding a secret), or a new one to cut at this branch's head",
            required: true,
            type: "string",
          },
        },
      },
    },
    permissions: { contents: "read" },
    jobs,
  };
  return { doc, comments };
}

// ---------------------------------------------------------------------------------------------
// compose.toolfactory.yaml — when openclaw-native or hermes-native is selected.
// ---------------------------------------------------------------------------------------------

function composeDocument(project: Project): Record<string, unknown> | undefined {
  const openclawSelected = has(project, "openclaw-native");
  const hermesSelected = has(project, "hermes-native");
  if (!openclawSelected && !hermesSelected) return undefined;

  const requiresBrowser = project.operations.some((op) => op.requires.includes("browser"));
  const services: Record<string, unknown> = {};

  if (openclawSelected) {
    services.openclaw = {
      image: `ghcr.io/openclaw/openclaw:latest${requiresBrowser ? "-browser" : ""}`,
      volumes: [".:/work", "PLUGIN_DATA:/data"],
      env_file: [".env"],
      // `--link` registers the mounted checkout in place: a plain install copies the whole tree,
      // node_modules/openclaw included, and trips the install-time symlink scan on the `file:`
      // core dependency. `--accept-capabilities` is what makes the install non-interactive.
      command: [
        "sh",
        "-c",
        `openclaw plugins install --link /work/${OPENCLAW_HOST_DIR} --force --accept-capabilities && openclaw plugins inspect ${project.identity.name} --runtime --json`,
      ],
    };
  }
  if (hermesSelected) {
    services.hermes = {
      // No published Hermes image exists; its own installer, pinned, in a stock image is the host.
      image: "buildpack-deps:bookworm",
      volumes: [".:/work", "PLUGIN_DATA:/data"],
      environment: { HERMES_HOME: "/data" },
      env_file: [".env"],
      command: [
        "bash",
        "-c",
        `${hermesInstall()} && hermes plugins doctor /work/${hermesPluginDir(project)} --ci`,
      ],
    };
  }
  return { services, volumes: { PLUGIN_DATA: {} } };
}

// ---------------------------------------------------------------------------------------------
// .env.example — always: every config key, from the one credential declaration (§6).
// ---------------------------------------------------------------------------------------------

function envExample(project: Project): string {
  const properties = configProperties(project);
  const required = new Set(requiredConfig(project));
  const keys = Object.keys(properties);
  const lines = [
    "# Generated by toolfactory from dev.toolfactory/tool.json `config`. Copy to `.env` and fill in.",
  ];
  if (keys.length === 0) lines.push("# No configuration keys are declared yet.");
  for (const key of keys) {
    const property = properties[key] as Record<string, unknown>;
    const sensitive = isSensitive(property);
    const meta = (property["x-toolfactory"] ?? {}) as { url?: string };
    const description = typeof property.description === "string" ? property.description : key;
    const tags = [required.has(key) ? "required" : "optional", sensitive ? "secret" : undefined]
      .filter(Boolean)
      .join(", ");
    lines.push(
      "",
      `# ${description} (${tags})${meta.url ? ` — get one: ${meta.url}` : ""}`,
      `${envName(key)}=`,
    );
  }
  const release = registries(project).filter((row) => row.secrets.length);
  if (release.length) {
    lines.push(
      "",
      "# Release credentials (repository secrets; `toolfactory bootstrap-repo` pushes them from .env,",
      "# `toolfactory secrets status` explains each). Leave one empty to skip that registry.",
    );
    for (const row of release) {
      lines.push("", `# ${row.id}: ${row.url}`, ...row.secrets.map((name) => `${name}=`));
    }
  }
  return `${lines.join("\n")}\n`;
}

// ---------------------------------------------------------------------------------------------
// renovate.json — always: config:recommended already spans npm/PyPI/Actions/Docker (C9).
// ---------------------------------------------------------------------------------------------

function renovatePatch(): Record<string, unknown> {
  return {
    $schema: "https://docs.renovatebot.com/renovate-schema.json",
    // `group:all` is Renovate's own preset for one PR per run rather than one per dependency;
    // writing the rule out by hand would only own a key the author needs for their own pins.
    extends: ["config:recommended", "group:all"],
    // Mirrors OpenClaw's own minimumReleaseAge.
    minimumReleaseAge: "7 days",
    // These files are projections of dev.toolfactory/tool.json and are SHA-locked: a Renovate PR
    // editing one makes `toolfactory check` fail and the next `toolfactory build` reverts it.
    // Upgrading what they pin is a toolfactory version bump (§8 C6).
    ignorePaths: [".github/workflows/**", "hosts/*/package.json", "web/package.json"],
  };
}

export const surface: Surface = {
  id: "workflows",
  plan(project) {
    const files: PlannedFile[] = [
      {
        kind: "file",
        path: ".github/workflows/ci.yml",
        content: YAML_HEADER + yml(ciDocument(project)),
      },
    ];

    const release = releaseDocument(project);
    if (release) {
      const header = [
        YAML_HEADER.trimEnd(),
        ...release.comments.map((line) => (line ? `# ${line}` : "#")),
        "",
        "",
      ].join("\n");
      files.push({
        kind: "file",
        path: ".github/workflows/release.yml",
        content: header + yml(release.doc),
      });
    }

    const compose = composeDocument(project);
    if (compose) {
      files.push({
        kind: "file",
        path: "compose.toolfactory.yaml",
        content: YAML_HEADER + yml(compose),
      });
    }

    files.push({ kind: "file", path: ".env.example", content: envExample(project) });
    // A merge file: an author's own keys (a `customManagers` for pins in their source) survive.
    files.push({
      kind: "merge",
      path: "renovate.json",
      format: "json",
      patch: renovatePatch(),
      owned: ["extends", "ignorePaths"],
    });

    return files;
  },
};
